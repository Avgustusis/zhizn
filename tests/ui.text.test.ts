import { describe, expect, it } from 'vitest'
import { compactLines, layoutSrc, noteBeyondLabel, wordsFromSrc } from '../src/ui/text.ts'

describe('Текст карты на экране (замечания Августа 26.11)', () => {
  it('правило по строкам: условия — каждое с новой строки, подпись группы висит слева', () => {
    expect(layoutSrc('Теизм: +1 псих. — молитва и общий стол. Секуляризм: −1 псих. — постояли и разошлись. Нейтрально: ничего'))
      .toEqual([{ lines: ['Теизм: +1 псих. — молитва и общий стол.', 'Секуляризм: −1 псих. — постояли и разошлись.', 'Нейтрально: ничего'] }])
    expect(layoutSrc('🎲 Ловкость 12: успех — только синяк, +1 псих. (герой дня); провал — −2 физ., +1 Харизма (автографы)'))
      .toEqual([{ label: '🎲 Ловкость 12:', lines: ['успех — только синяк, +1 псих. (герой дня);', 'провал — −2 физ., +1 Харизма (автографы)'] }])
    expect(layoutSrc('Страна: Теократия: стабильность +1 — знамение истолковали верно · Игроки: Все: +1 Мудрость до 7 или +1 псих., по выбору').map((g) => g.label))
      .toEqual(['Страна:', 'Игроки:'])
    // «; Финансы и Сплочённость — броски» — не новое условие; «Иначе» — новое.
    expect(layoutSrc('Если класс семьи Армия или Полиция: класс семьи становится Народ (−1 псих. — понижение); Финансы и Сплочённость — броски «Удар по семье». Иначе: только Финансы')[0].lines).toHaveLength(2)
    // Под проверкой висят только её исходы.
    expect(layoutSrc('🎲 Выносливость 12: успех — +1 физ.; провал — −2 физ. Возм. +10 и выше: принесли домой')).toHaveLength(2)
    // Полюса культуры после «;» — с новой строки, под вариантом.
    expect(layoutSrc('А) к дяде: +2 возм.; Фамилизм — Сплочённость +1; Институции — d6 1–2: −1 к #статус')[0]).toEqual({ label: 'А) к дяде:', lines: ['+2 возм.;', 'Фамилизм — Сплочённость +1;', 'Институции — d6 1–2: −1 к #статус'] })
  })

  it('варианты без «А) Б)» — словами карты из скобок; правило обрезано до первого варианта', () => {
    const src = '−1 возм. и одно на выбор: спорт (+1 Сила, Выносливость или Ловкость), музыка или театр (+1 Харизма), шахматы (+1 Интеллект)'
    expect(wordsFromSrc(src, ['спорт', 'музыка или театр', 'шахматы'])).toEqual({
      words: ['Спорт (+1 Сила, Выносливость или Ловкость)', 'Музыка или театр (+1 Харизма)', 'Шахматы (+1 Интеллект)'], head: '−1 возм. и одно на выбор:',
    })
    expect(wordsFromSrc('Все: +1 Мудрость до 7 или +1 псих., по выбору', ['+1 Мудрость', '+1 псих.'])).toBeUndefined()
  })

  it('пояснение варианта без повтора названия', () => {
    expect(noteBeyondLabel('+1 Мудрость', '+1 Мудрость (до 7)')).toBe('(до 7)')
    expect(noteBeyondLabel('+1 псих.', '+1 псих.')).toBe('')
    expect(noteBeyondLabel('Спорт', '+1 к одной на выбор')).toBe('+1 к одной на выбор')
  })

  it('условие со своими вариантами («Есть Партнёр: А) … Б) …») и скобки не рвутся', () => {
    const g = layoutSrc('Есть Партнёр: А) свадьба — Супруг, −2 возм.; Б) жить вместе — +1 псих.; В) расстаться — −2 псих. Уже в браке: ничего. Нет партнёра: А) искать — 🎲 Красота 12; Б) сватовство: 🎲 Сплочённость 9 (Традиция +1; Фамилизм +1; теократия +2) — успех: свадьба; провал: −1 псих.; В) жить одному — +1 возм.')
    expect(g.map((x) => x.label)).toEqual(['Есть Партнёр:', undefined, 'Нет партнёра:'])
    expect(g[0].lines).toHaveLength(3)
    expect(g[2].lines).toEqual(['А) искать — 🎲 Красота 12;', 'Б) сватовство: 🎲 Сплочённость 9 (Традиция +1; Фамилизм +1; теократия +2) — успех: свадьба;', 'провал: −1 псих.;', 'В) жить одному — +1 возм.'])
  })

  it('разбор эффекта — фразой, а не столбиком', () => {
    expect(compactLines(['если эмигрант:', '  +1 возм.', 'иначе:', '  +2 возм.', 'если культура за полюс «Фамилизм»:', '  +1 возм.'])).toBe('Если эмигрант — +1 возм.; иначе — +2 возм.; Фамилизм — +1 возм.')
    expect(compactLines(['🎲 Ловкость 12', '  успех:', '    +1 Ловкость', '  провал:', '    −3 физ.'])).toBe('🎲 Ловкость 12: успех — +1 Ловкость; провал — −3 физ.')
  })
})
