// ── Условия ─────────────────────────────────────────────────────────────

const all = (...c: Cond[]): Cond => (c.length === 1 ? c[0] : { all: c })
const not = (c: Cond): Cond => ({ not: c })
const ideo = (...i: Extract<Cond, { ideo: unknown }>['ideo']): Cond => ({ ideo: i })
const psyFrom = (n: number): Cond => ({ p: 'псих', gte: n })
const physFrom = (n: number): Cond => ({ p: 'физ', gte: n })
const has = (n: string): Cond => ({ has: n })
const rule = (r: string): Cond => ({ rule: r })
const OLD: Cond = { seg: ['Старость', 'Древность'] }

/** Срыв: до конца отрезка открыты только больница, психолог, семья и обряд. */
/** Срыв или карантин (до следующего круга: из работ только Подработка, из рынка — больница и семья). */
const NO_BREAK = all(not(rule('срыв')), not(rule('карантин')))
/** «Без документов»: только Подработка, ловушки, больница и обряд. */
const DOCS = not(has('Без документов'))
/** Психика −5 и ниже закрывает спортзал, курсы, салон, путешествие, хобби, переработку. */
const CALM = psyFrom(-4)
/** Психика −8 и ниже закрывает вдобавок любую работу и храм (Усердие держится на работе до −8). */
const ON_FEET = psyFrom(-7)
const WORKS = { all: [{ any: [psyFrom(-7), { all: [{ char: 'Усердие' }, psyFrom(-8)] }] }, { not: { rule: 'на пенсии' } }] } as Cond
/** Развилка «Пенсия»: «учить молодых» — из работ только Подработка (решено в 3г по тексту карты). */
const TEACHING = { rule: 'учит молодых' } as Cond
/** Физическое −5 и ниже закрывает спортзал, путешествие, переработку, бордель. */
const BODY = physFrom(-4)
/** Ловушка незаконна (идеологии из «Поправок по идеологии»); на периферии рынок не регулируется. */
/** Ловушка незаконна: в названных идеологиях и при полицейском государстве (все ловушки); на периферии и при вольнице — законна. */
const illegal = (...i: Extract<Cond, { ideo: unknown }>['ideo']): Cond =>
  all(not({ pos: ['периферия'] }), not(ideo('Вольница')), ideo(...i, 'Полицейское государство'))
const lawRisk = (cond: Cond, range = '3'): Node => ({ if: cond, then: [{ d6: { [range]: [{ rule: 'закон ловушки' }] } }] })

