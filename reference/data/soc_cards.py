def trace_badge(t):
    """строка на карте: ✊ ветка → канал"""
    d, s, no, n, br, ch = t
    if ch == '—': return '✊ ' + br
    return '✊ %s → %s' % (br, 'канал твоего класса' if ch == 'свой' else ch)


